// Colourways, likes, saves, wears and notifications (docs/colourways-plan.md).
//
// A colourway is one set of colours on a ring: a colour per part, and optionally a painted
// texture and a picture. The ring's author colours it too; anyone signed in may recolour any
// ring (like a fork), and the author is told. The author picks the ring's cover from their
// own colourways only, may feature or hide other people's, and may delete the ring. Nothing is
// really deleted: a deleted ring or colourway stays in people's records, marked removed, and
// can no longer be worn.
//
// Likes and saves count people, not presses: one row per person and thing.

import { randomBytes } from "node:crypto";
import { RenderError } from "./render.js";

export const SOCIAL_SCHEMA = [
  `CREATE TABLE IF NOT EXISTS colourways (
     id TEXT PRIMARY KEY,
     piece_id TEXT NOT NULL REFERENCES pieces(id),
     user_id INTEGER NOT NULL REFERENCES users(id),
     author TEXT NOT NULL,
     paints TEXT NOT NULL,
     has_texture INTEGER NOT NULL DEFAULT 0,
     has_picture INTEGER NOT NULL DEFAULT 0,
     featured INTEGER NOT NULL DEFAULT 0,
     hidden INTEGER NOT NULL DEFAULT 0,
     deleted INTEGER NOT NULL DEFAULT 0,
     created_at BIGINT NOT NULL
   )`,
  `CREATE INDEX IF NOT EXISTS colourways_piece ON colourways (piece_id)`,
  `CREATE INDEX IF NOT EXISTS colourways_user ON colourways (user_id)`,
  `CREATE TABLE IF NOT EXISTS likes (
     user_id INTEGER NOT NULL REFERENCES users(id),
     kind TEXT NOT NULL,
     target_id TEXT NOT NULL,
     created_at BIGINT NOT NULL,
     PRIMARY KEY (user_id, kind, target_id)
   )`,
  `CREATE TABLE IF NOT EXISTS saves (
     user_id INTEGER NOT NULL REFERENCES users(id),
     piece_id TEXT NOT NULL REFERENCES pieces(id),
     created_at BIGINT NOT NULL,
     PRIMARY KEY (user_id, piece_id)
   )`,
  `CREATE TABLE IF NOT EXISTS wears (
     user_id INTEGER NOT NULL REFERENCES users(id),
     piece_id TEXT NOT NULL REFERENCES pieces(id),
     colourway_id TEXT NOT NULL,
     first_at BIGINT NOT NULL,
     last_at BIGINT NOT NULL,
     PRIMARY KEY (user_id, piece_id, colourway_id)
   )`,
  `CREATE TABLE IF NOT EXISTS notifications (
     id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
     user_id INTEGER NOT NULL REFERENCES users(id),
     kind TEXT NOT NULL,
     piece_id TEXT NOT NULL,
     colourway_id TEXT,
     actor TEXT NOT NULL,
     created_at BIGINT NOT NULL,
     seen INTEGER NOT NULL DEFAULT 0
   )`,
  `CREATE INDEX IF NOT EXISTS notifications_user ON notifications (user_id)`,
];

/** Columns added to pieces after it was first made: [name, definition]. */
export const PIECE_COLUMNS = [
  ["cover_colourway", "TEXT"],
  ["deleted", "INTEGER NOT NULL DEFAULT 0"],
];

const COLOURWAY_ID = /^cw[0-9a-f]{16}$/;
const ARGB = /^-?\d{1,10}$/;
const MAX_PARTS = 8;
/** What a wear of the ring as its author left it (no colourway) is stored under. */
const ORIGINAL = "";

export const isColourwayId = (id) => typeof id === "string" && COLOURWAY_ID.test(id);

/** A colour per part, as { "0": argb, "1": argb }: checked, then kept as JSON text. */
function checkPaints(paints) {
  if (!paints || typeof paints !== "object" || Array.isArray(paints)) {
    throw new RenderError(400, "paints must be an object of part -> colour");
  }
  const entries = Object.entries(paints);
  if (entries.length > MAX_PARTS) throw new RenderError(400, "too many parts");
  const clean = {};
  for (const [part, colour] of entries) {
    if (!/^\d$/.test(part) || !ARGB.test(String(colour))) throw new RenderError(400, "bad colour");
    clean[part] = Number(colour) | 0;
  }
  return JSON.stringify(clean);
}

export function createSocial({ sql, one, now }) {
  const count = async (query, params) => Number((await one(query, params))?.n ?? 0);

  async function livePiece(pieceId) {
    const row = await one("SELECT id, user_id, author, name, deleted FROM pieces WHERE id = ? AND ready = 1", [pieceId]);
    if (!row) throw new RenderError(404, "No such ring.");
    return { ...row, user_id: row.user_id === null ? null : Number(row.user_id), deleted: Number(row.deleted) === 1 };
  }

  async function colourwayRow(id) {
    if (!isColourwayId(id)) throw new RenderError(404, "No such colourway.");
    const row = await one("SELECT * FROM colourways WHERE id = ?", [id]);
    if (!row || Number(row.deleted) === 1) throw new RenderError(404, "No such colourway.");
    return { ...row, user_id: Number(row.user_id) };
  }

  async function notify(userId, kind, pieceId, colourwayId, actor) {
    if (userId === null) return;
    await sql.run(
      "INSERT INTO notifications (user_id, kind, piece_id, colourway_id, actor, created_at) VALUES (?, ?, ?, ?, ?, ?)",
      [userId, kind, pieceId, colourwayId, actor, now()],
    );
  }

  /**
   * Saves a colourway on a ring. [files] say whether a texture and a picture were stored with
   * it (the caller stores them under the returned id). The ring's author is told when someone
   * else recolours it.
   */
  async function saveColourway({ pieceId, user, paints, hasTexture = false, hasPicture = false, id }) {
    const piece = await livePiece(pieceId);
    if (piece.deleted) throw new RenderError(410, "This ring has been removed by its author.");
    const colourwayId = id ?? newColourwayId();
    await sql.run(
      `INSERT INTO colourways (id, piece_id, user_id, author, paints, has_texture, has_picture, created_at)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
      [colourwayId, pieceId, user.id, user.name, checkPaints(paints), hasTexture ? 1 : 0, hasPicture ? 1 : 0, now()],
    );
    if (piece.user_id !== user.id) await notify(piece.user_id, "recoloured", pieceId, colourwayId, user.name);
    return colourwayId;
  }

  function newColourwayId() {
    return `cw${randomBytes(8).toString("hex")}`;
  }

  /** The colourway's maker removes it. It stays in records, marked removed. */
  async function deleteColourway(id, user) {
    const row = await colourwayRow(id);
    if (row.user_id !== user.id) throw new RenderError(403, "Only its maker can delete this colourway.");
    await sql.run("UPDATE colourways SET deleted = 1 WHERE id = ?", [id]);
    await sql.run("UPDATE pieces SET cover_colourway = NULL WHERE cover_colourway = ?", [id]);
  }

  /** The ring's author, about a colourway on their ring made by someone else. */
  async function authorOfOthers(id, user) {
    const row = await colourwayRow(id);
    const piece = await livePiece(row.piece_id);
    if (piece.user_id !== user.id) throw new RenderError(403, "Only the ring's author can do this.");
    if (row.user_id === user.id) throw new RenderError(400, "This is your own colourway.");
    return { row, piece };
  }

  async function featureColourway(id, user, on) {
    const { row } = await authorOfOthers(id, user);
    await sql.run("UPDATE colourways SET featured = ? WHERE id = ?", [on ? 1 : 0, id]);
    if (on && Number(row.featured) !== 1) await notify(row.user_id, "featured", row.piece_id, id, user.name);
  }

  async function hideColourway(id, user, on) {
    await authorOfOthers(id, user);
    await sql.run("UPDATE colourways SET hidden = ? WHERE id = ?", [on ? 1 : 0, id]);
  }

  /** The cover is one of the author's own colourways on this ring, or null for the render. */
  async function setCover(pieceId, colourwayId, user) {
    const piece = await livePiece(pieceId);
    if (piece.user_id !== user.id) throw new RenderError(403, "Only the ring's author can choose its cover.");
    if (colourwayId !== null) {
      const row = await colourwayRow(colourwayId);
      if (row.piece_id !== pieceId || row.user_id !== user.id) {
        throw new RenderError(400, "The cover must be one of your own colourways on this ring.");
      }
    }
    await sql.run("UPDATE pieces SET cover_colourway = ? WHERE id = ?", [colourwayId, pieceId]);
  }

  async function deletePiece(pieceId, user) {
    const piece = await livePiece(pieceId);
    if (piece.user_id !== user.id) throw new RenderError(403, "Only the ring's author can delete it.");
    await sql.run("UPDATE pieces SET deleted = 1 WHERE id = ?", [pieceId]);
  }

  async function like(user, kind, targetId, on) {
    if (kind === "piece") await livePiece(targetId);
    else if (kind === "colourway") await colourwayRow(targetId);
    else throw new RenderError(400, "kind must be piece or colourway");
    if (on) {
      await sql.run(
        "INSERT INTO likes (user_id, kind, target_id, created_at) VALUES (?, ?, ?, ?) ON CONFLICT DO NOTHING",
        [user.id, kind, targetId, now()],
      );
    } else {
      await sql.run("DELETE FROM likes WHERE user_id = ? AND kind = ? AND target_id = ?", [user.id, kind, targetId]);
    }
  }

  async function save(user, pieceId, on) {
    await livePiece(pieceId);
    if (on) {
      await sql.run("INSERT INTO saves (user_id, piece_id, created_at) VALUES (?, ?, ?) ON CONFLICT DO NOTHING", [
        user.id,
        pieceId,
        now(),
      ]);
    } else {
      await sql.run("DELETE FROM saves WHERE user_id = ? AND piece_id = ?", [user.id, pieceId]);
    }
  }

  /** Records that [user] put on a ring, as its author left it or in a colourway. */
  async function wear(user, pieceId, colourwayId = null) {
    const piece = await livePiece(pieceId);
    if (piece.deleted) throw new RenderError(410, "This ring has been removed by its author.");
    if (colourwayId !== null) {
      const row = await colourwayRow(colourwayId);
      if (row.piece_id !== pieceId) throw new RenderError(400, "That colourway is for another ring.");
    }
    const at = now();
    await sql.run(
      `INSERT INTO wears (user_id, piece_id, colourway_id, first_at, last_at) VALUES (?, ?, ?, ?, ?)
       ON CONFLICT (user_id, piece_id, colourway_id) DO UPDATE SET last_at = excluded.last_at`,
      [user.id, pieceId, colourwayId ?? ORIGINAL, at, at],
    );
  }

  async function pieceCounts(pieceId, viewer) {
    return {
      likes: await count("SELECT COUNT(*) AS n FROM likes WHERE kind = 'piece' AND target_id = ?", [pieceId]),
      saves: await count("SELECT COUNT(*) AS n FROM saves WHERE piece_id = ?", [pieceId]),
      wearers: await count("SELECT COUNT(DISTINCT user_id) AS n FROM wears WHERE piece_id = ?", [pieceId]),
      likedByMe: viewer
        ? (await count("SELECT COUNT(*) AS n FROM likes WHERE kind = 'piece' AND target_id = ? AND user_id = ?", [pieceId, viewer.id])) > 0
        : false,
      savedByMe: viewer
        ? (await count("SELECT COUNT(*) AS n FROM saves WHERE piece_id = ? AND user_id = ?", [pieceId, viewer.id])) > 0
        : false,
    };
  }

  function colourwayOut(row) {
    return {
      id: row.id,
      pieceId: row.piece_id,
      author: row.author,
      paints: JSON.parse(row.paints),
      hasTexture: Number(row.has_texture) === 1,
      hasPicture: Number(row.has_picture) === 1,
      featured: Number(row.featured) === 1,
      hidden: Number(row.hidden) === 1,
      createdAt: Number(row.created_at),
    };
  }

  async function colourwayCounts(id, viewer) {
    return {
      likes: await count("SELECT COUNT(*) AS n FROM likes WHERE kind = 'colourway' AND target_id = ?", [id]),
      wearers: await count("SELECT COUNT(DISTINCT user_id) AS n FROM wears WHERE colourway_id = ?", [id]),
      likedByMe: viewer
        ? (await count("SELECT COUNT(*) AS n FROM likes WHERE kind = 'colourway' AND target_id = ? AND user_id = ?", [id, viewer.id])) > 0
        : false,
    };
  }

  /**
   * One ring, as its page shows it: the ring, its counts, the author's colourways, and
   * everyone else's (featured first, then newest). Hidden ones show only to the author.
   */
  async function pieceDetail(pieceId, viewer = null) {
    const piece = await livePiece(pieceId);
    if (piece.deleted && piece.user_id !== viewer?.id) throw new RenderError(410, "This ring has been removed by its author.");
    const isAuthor = viewer !== null && piece.user_id === viewer.id;
    const full = await one(
      `SELECT id, author, name, material, created_at AS "createdAt", cover_colourway AS "cover" FROM pieces WHERE id = ?`,
      [pieceId],
    );
    const rows = await sql.all("SELECT * FROM colourways WHERE piece_id = ? AND deleted = 0 ORDER BY created_at DESC", [pieceId]);
    const own = [];
    const others = [];
    for (const row of rows) {
      const out = { ...colourwayOut(row), ...(await colourwayCounts(row.id, viewer)) };
      if (piece.user_id !== null && Number(row.user_id) === piece.user_id) own.push(out);
      else if (!out.hidden || isAuthor) others.push(out);
    }
    others.sort((a, b) => Number(b.featured) - Number(a.featured) || b.createdAt - a.createdAt);
    return {
      piece: { ...full, createdAt: Number(full.createdAt), cover: full.cover ?? null, deleted: piece.deleted, isAuthor },
      ...(await pieceCounts(pieceId, viewer)),
      authorColourways: own,
      otherColourways: others,
    };
  }

  /** Gallery counts and covers for every live ring, by id. */
  async function galleryExtras(ids) {
    const out = {};
    for (const id of ids) {
      const row = await one(`SELECT cover_colourway AS "cover" FROM pieces WHERE id = ?`, [id]);
      const cover = row?.cover ? await one("SELECT * FROM colourways WHERE id = ? AND deleted = 0", [row.cover]) : null;
      out[id] = {
        likes: await count("SELECT COUNT(*) AS n FROM likes WHERE kind = 'piece' AND target_id = ?", [id]),
        saves: await count("SELECT COUNT(*) AS n FROM saves WHERE piece_id = ?", [id]),
        cover: cover ? colourwayOut(cover) : null,
      };
    }
    return out;
  }

  /**
   * Everything of mine: rings I drew, colourways I made on any ring, rings I saved, and what
   * I wore. A removed ring or colourway is still listed, marked so, and cannot be worn.
   */
  async function mine(user) {
    const pieceStatus = (row) => (Number(row.deleted) === 1 ? "removed" : "live");
    const rings = await sql.all(
      `SELECT id, name, material, created_at AS "createdAt", cover_colourway AS "cover", deleted FROM pieces
       WHERE user_id = ? AND ready = 1 AND deleted = 0 ORDER BY created_at DESC`,
      [user.id],
    );
    const colourways = await sql.all(
      `SELECT colourways.*, pieces.name AS piece_name, pieces.author AS piece_author, pieces.user_id AS piece_user,
              pieces.deleted AS piece_deleted
       FROM colourways JOIN pieces ON pieces.id = colourways.piece_id
       WHERE colourways.user_id = ? AND colourways.deleted = 0 ORDER BY colourways.created_at DESC`,
      [user.id],
    );
    const saved = await sql.all(
      `SELECT pieces.id, pieces.name, pieces.author, pieces.deleted, saves.created_at AS "savedAt" FROM saves
       JOIN pieces ON pieces.id = saves.piece_id WHERE saves.user_id = ? ORDER BY saves.created_at DESC`,
      [user.id],
    );
    const wears = await sql.all(
      `SELECT wears.piece_id, wears.colourway_id, wears.last_at, pieces.name, pieces.author, pieces.deleted,
              colourways.deleted AS cw_deleted, colourways.paints
       FROM wears JOIN pieces ON pieces.id = wears.piece_id
       LEFT JOIN colourways ON colourways.id = wears.colourway_id
       WHERE wears.user_id = ? ORDER BY wears.last_at DESC`,
      [user.id],
    );
    return {
      rings: rings.map((r) => ({ id: r.id, name: r.name, material: r.material, createdAt: Number(r.createdAt), cover: r.cover ?? null })),
      colourways: colourways.map((r) => ({
        ...colourwayOut(r),
        pieceName: r.piece_name,
        pieceAuthor: r.piece_author,
        // On a ring I drew, or a recolour of someone else's.
        onMyRing: r.piece_user !== null && Number(r.piece_user) === user.id,
        status: Number(r.piece_deleted) === 1 ? "removed" : Number(r.hidden) === 1 ? "hidden" : "live",
      })),
      saved: saved.map((r) => ({ id: r.id, name: r.name, author: r.author, status: pieceStatus(r), savedAt: Number(r.savedAt) })),
      wears: wears.map((r) => ({
        pieceId: r.piece_id,
        colourwayId: r.colourway_id || null,
        name: r.name,
        author: r.author,
        paints: r.paints ? JSON.parse(r.paints) : null,
        lastAt: Number(r.last_at),
        // Wearable again only if neither the ring nor the colourway was removed.
        status: Number(r.deleted) === 1 || Number(r.cw_deleted) === 1 ? "removed" : "live",
      })),
    };
  }

  async function notifications(user) {
    const rows = await sql.all(
      `SELECT notifications.id, kind, piece_id, colourway_id, actor, notifications.created_at, seen, pieces.name AS piece_name
       FROM notifications JOIN pieces ON pieces.id = notifications.piece_id
       WHERE notifications.user_id = ? ORDER BY notifications.created_at DESC, notifications.id DESC`,
      [user.id],
    );
    return rows.map((r) => ({
      id: Number(r.id),
      kind: r.kind,
      pieceId: r.piece_id,
      pieceName: r.piece_name,
      colourwayId: r.colourway_id,
      actor: r.actor,
      createdAt: Number(r.created_at),
      seen: Number(r.seen) === 1,
    }));
  }

  async function markNotificationsSeen(user) {
    await sql.run("UPDATE notifications SET seen = 1 WHERE user_id = ?", [user.id]);
  }

  return {
    newColourwayId,
    saveColourway,
    deleteColourway,
    featureColourway,
    hideColourway,
    setCover,
    deletePiece,
    like,
    save,
    wear,
    pieceDetail,
    galleryExtras,
    mine,
    notifications,
    markNotificationsSeen,
  };
}
