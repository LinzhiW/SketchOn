// Accounts and pieces, in SQLite on a computer (server/data/sketchon.db) or in Postgres in the
// cloud (Supabase). The logic below is written once; a small adapter runs the SQL on either.
//
// Passwords are stored as scrypt hashes with a per-user salt, never as text. A login gives
// the app a random token; only the token's SHA-256 is stored, so the database alone cannot
// be used to sign in. Tokens last 90 days.
//
// Pieces (finished rings) record who made them. A piece is added when its 3D job starts and
// marked ready when its model is saved; the gallery shows ready pieces only. Pieces made
// before accounts existed are imported with the author name given at start-up.

import { createHash, randomBytes, scryptSync, timingSafeEqual } from "node:crypto";
import { RenderError } from "./render.js";

const NAME = /^[A-Za-z0-9][A-Za-z0-9 ._-]{1,19}$/;
const MIN_PASSWORD = 6;
const MAX_PASSWORD = 100;
const TOKEN_DAYS = 90;
const DAY_MS = 24 * 60 * 60 * 1000;

const hashToken = (token) => createHash("sha256").update(token).digest("hex");
const hashPassword = (password, salt) => scryptSync(password, salt, 64);

// Written so both SQLite and Postgres accept it. "?" placeholders become $1.. for Postgres.
const SCHEMA = [
  `CREATE TABLE IF NOT EXISTS users (
     id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
     name TEXT NOT NULL,
     salt BYTEA NOT NULL,
     hash BYTEA NOT NULL,
     created_at BIGINT NOT NULL
   )`,
  `CREATE UNIQUE INDEX IF NOT EXISTS users_name ON users (lower(name))`,
  `CREATE TABLE IF NOT EXISTS tokens (
     hash TEXT PRIMARY KEY,
     user_id INTEGER NOT NULL REFERENCES users(id),
     expires_at BIGINT NOT NULL
   )`,
  `CREATE TABLE IF NOT EXISTS pieces (
     id TEXT PRIMARY KEY,
     user_id INTEGER REFERENCES users(id),
     author TEXT,
     name TEXT,
     material TEXT,
     created_at BIGINT NOT NULL,
     ready INTEGER NOT NULL DEFAULT 0
   )`,
];

/** SQLite through node:sqlite. Its SQL dialect needs a few words swapped. */
async function sqliteAdapter(path) {
  const { DatabaseSync } = await import("node:sqlite");
  const db = new DatabaseSync(path);
  if (path !== ":memory:") db.exec("PRAGMA journal_mode = WAL");
  const dialect = (sql) =>
    sql
      .replace("INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY", "INTEGER PRIMARY KEY")
      .replaceAll("BYTEA", "BLOB")
      .replaceAll("BIGINT", "INTEGER");
  // A database made before pieces had a "ready" column gets one, with the old pieces ready.
  const migrate = () => {
    const columns = db.prepare("PRAGMA table_info(pieces)").all().map((c) => c.name);
    if (columns.length && !columns.includes("ready")) {
      db.exec("ALTER TABLE pieces ADD COLUMN ready INTEGER NOT NULL DEFAULT 1");
    }
  };
  return {
    async all(sql, params = []) {
      return db.prepare(dialect(sql)).all(...params).map((row) => ({ ...row }));
    },
    async run(sql, params = []) {
      db.prepare(dialect(sql)).run(...params);
    },
    async exec(sql) {
      if (sql.startsWith("CREATE TABLE IF NOT EXISTS pieces")) migrate();
      db.exec(dialect(sql));
    },
    async close() {
      db.close();
    },
  };
}

/** Postgres through node-postgres, for Supabase. */
async function postgresAdapter(url) {
  const { default: pg } = await import("pg");
  // Supabase requires TLS; its certificate chain is not in Node's default store on every host.
  const pool = new pg.Pool({ connectionString: url, ssl: { rejectUnauthorized: false }, max: 5 });
  const numbered = (sql) => {
    let n = 0;
    return sql.replace(/\?/g, () => `$${++n}`);
  };
  // BIGINT comes back as a string by default; these numbers are milliseconds, safe as numbers.
  pg.types.setTypeParser(20, (v) => Number(v));
  return {
    async all(sql, params = []) {
      return (await pool.query(numbered(sql), params)).rows;
    },
    async run(sql, params = []) {
      await pool.query(numbered(sql), params);
    },
    async exec(sql) {
      await pool.query(sql);
    },
    async close() {
      await pool.end();
    },
  };
}

/**
 * Opens the database: Postgres when [url] starts with postgres, otherwise a SQLite file (or
 * memory, for tests).
 */
export async function openDb(url = ":memory:", { now = () => Date.now() } = {}) {
  const sql = /^postgres(ql)?:\/\//.test(url) ? await postgresAdapter(url) : await sqliteAdapter(url);
  for (const statement of SCHEMA) await sql.exec(statement);
  const one = async (query, params) => (await sql.all(query, params))[0] ?? null;

  function checkCredentials(name, password) {
    if (typeof name !== "string" || !NAME.test(name.trim())) {
      throw new RenderError(400, "Names are 2 to 20 letters, numbers, spaces, dots, dashes or underscores.");
    }
    if (typeof password !== "string" || password.length < MIN_PASSWORD || password.length > MAX_PASSWORD) {
      throw new RenderError(400, `Passwords are ${MIN_PASSWORD} to ${MAX_PASSWORD} characters.`);
    }
  }

  async function issueToken(userId) {
    const token = randomBytes(32).toString("hex");
    await sql.run("INSERT INTO tokens (hash, user_id, expires_at) VALUES (?, ?, ?)", [
      hashToken(token),
      userId,
      now() + TOKEN_DAYS * DAY_MS,
    ]);
    return token;
  }

  async function signUp(name, password) {
    checkCredentials(name, password);
    const clean = name.trim();
    if (await one("SELECT 1 AS taken FROM users WHERE lower(name) = lower(?)", [clean])) {
      throw new RenderError(409, "That name is taken.");
    }
    const salt = randomBytes(16);
    const row = await one("INSERT INTO users (name, salt, hash, created_at) VALUES (?, ?, ?, ?) RETURNING id", [
      clean,
      salt,
      hashPassword(password, salt),
      now(),
    ]);
    const user = { id: Number(row.id), name: clean };
    return { token: await issueToken(user.id), user };
  }

  async function logIn(name, password) {
    const row =
      typeof name === "string"
        ? await one("SELECT id, name, salt, hash FROM users WHERE lower(name) = lower(?)", [name.trim()])
        : null;
    // The same message whether the name or the password is wrong.
    const wrong = new RenderError(401, "Wrong name or password.");
    if (!row || typeof password !== "string") throw wrong;
    const stored = Buffer.from(row.hash);
    const given = hashPassword(password, Buffer.from(row.salt));
    if (given.length !== stored.length || !timingSafeEqual(given, stored)) throw wrong;
    return { token: await issueToken(Number(row.id)), user: { id: Number(row.id), name: row.name } };
  }

  async function userForToken(token) {
    if (typeof token !== "string" || !token) return null;
    const row = await one(
      "SELECT users.id, users.name, tokens.expires_at FROM tokens JOIN users ON users.id = tokens.user_id WHERE tokens.hash = ?",
      [hashToken(token)],
    );
    if (!row || Number(row.expires_at) < now()) return null;
    return { id: Number(row.id), name: row.name };
  }

  async function logOut(token) {
    if (typeof token === "string") await sql.run("DELETE FROM tokens WHERE hash = ?", [hashToken(token)]);
  }

  async function addPiece({ id, user, name, material, createdAt, ready = false }) {
    await sql.run(
      `INSERT INTO pieces (id, user_id, author, name, material, created_at, ready) VALUES (?, ?, ?, ?, ?, ?, ?)
       ON CONFLICT (id) DO UPDATE SET user_id = excluded.user_id, author = excluded.author, name = excluded.name,
         material = excluded.material, created_at = excluded.created_at`,
      [id, user?.id ?? null, user?.name ?? null, name ?? null, material ?? null, createdAt ?? now(), ready ? 1 : 0],
    );
  }

  async function markReady(id) {
    await sql.run("UPDATE pieces SET ready = 1 WHERE id = ?", [id]);
  }

  /** Only the piece's maker may name it. */
  async function renamePiece(id, name, user) {
    const row = await one("SELECT user_id FROM pieces WHERE id = ?", [id]);
    if (!row) throw new RenderError(404, "No such piece.");
    if (row.user_id !== null && Number(row.user_id) !== user?.id) {
      throw new RenderError(403, "Only its maker can name this piece.");
    }
    await sql.run("UPDATE pieces SET name = ? WHERE id = ?", [name, id]);
  }

  const columns = "id, author, name, material, created_at AS \"createdAt\"";
  const tidy = (row) => (row ? { ...row, createdAt: Number(row.createdAt) } : null);

  async function piece(id) {
    return tidy(await one(`SELECT ${columns} FROM pieces WHERE id = ?`, [id]));
  }

  /** Finished pieces, newest first. */
  async function pieces() {
    return (await sql.all(`SELECT ${columns} FROM pieces WHERE ready = 1 ORDER BY created_at DESC`)).map(tidy);
  }

  /** Imports a finished piece made before accounts, unless it is already known. */
  async function importLegacy(id, info, author) {
    if (await piece(id)) return false;
    await sql.run(
      "INSERT INTO pieces (id, user_id, author, name, material, created_at, ready) VALUES (?, NULL, ?, ?, ?, ?, 1)",
      [id, author, info?.name ?? null, info?.material ?? null, info?.createdAt ?? now()],
    );
    return true;
  }

  return {
    signUp,
    logIn,
    userForToken,
    logOut,
    addPiece,
    markReady,
    renamePiece,
    piece,
    pieces,
    importLegacy,
    close: () => sql.close(),
  };
}
